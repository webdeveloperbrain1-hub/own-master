-- Own Masters Phase 1 dashboard foundation.
-- Run this in the Supabase SQL editor for the project configured in .env.

create extension if not exists "pgcrypto";

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  email text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contracts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  contract_type text not null,
  status text not null default 'draft' check (status in ('draft', 'completed')),
  content text not null default 'This draft will be generated by the Own Masters Contract AI.',
  user_request text,
  selected_template_id text,
  selected_template_source_file text,
  wizard_answers jsonb not null default '{}'::jsonb,
  ai_recommendation jsonb,
  ai_risk_review jsonb,
  ai_summary text,
  ai_enabled boolean not null default true,
  risk_flags jsonb not null default '[]'::jsonb,
  last_ai_reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists contracts_user_id_updated_at_idx
  on public.contracts(user_id, updated_at desc);

alter table public.contracts add column if not exists selected_template_id text;
alter table public.contracts add column if not exists selected_template_source_file text;
alter table public.contracts add column if not exists wizard_answers jsonb not null default '{}'::jsonb;
alter table public.contracts add column if not exists ai_recommendation jsonb;
alter table public.contracts add column if not exists ai_risk_review jsonb;
alter table public.contracts add column if not exists ai_summary text;
alter table public.contracts add column if not exists ai_enabled boolean not null default true;
alter table public.contracts add column if not exists risk_flags jsonb not null default '[]'::jsonb;
alter table public.contracts add column if not exists last_ai_reviewed_at timestamptz;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists contracts_set_updated_at on public.contracts;
create trigger contracts_set_updated_at
before update on public.contracts
for each row execute function public.set_updated_at();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    coalesce(new.email, '')
  )
  on conflict (id) do update set
    name = excluded.name,
    email = excluded.email,
    updated_at = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.contracts enable row level security;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
on public.profiles for select
using (auth.uid() = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
on public.profiles for update
using (auth.uid() = id)
with check (auth.uid() = id);

drop policy if exists "Users can read their own contracts" on public.contracts;
create policy "Users can read their own contracts"
on public.contracts for select
using (auth.uid() = user_id);

drop policy if exists "Users can create their own contracts" on public.contracts;
create policy "Users can create their own contracts"
on public.contracts for insert
with check (auth.uid() = user_id);

drop policy if exists "Users can update their own contracts" on public.contracts;
create policy "Users can update their own contracts"
on public.contracts for update
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own contracts" on public.contracts;
create policy "Users can delete their own contracts"
on public.contracts for delete
using (auth.uid() = user_id);
