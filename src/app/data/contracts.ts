const DRAFT_PLACEHOLDER = 'This draft will be generated by the Own Masters Contract AI.';
const DEMO_USER_KEY = 'own_masters_demo_user';
const DEMO_CONTRACTS_KEY = 'own_masters_demo_contracts';

function isDemoMode() {
  return import.meta.env.DEV && window.localStorage.getItem(DEMO_USER_KEY) === 'true';
}

// Build an initial draft for a contract. Prefers the built-in template fill
// (position-based blanks, same approach as ContractFill) when a templateId is
// available; falls back to the deterministic generator for unknown types.
function buildInitialDraft(
  contractType: string,
  wizardAnswers: Record<string, unknown>,
  userRequest?: string | null,
  selectedTemplateId?: string | null,
): string {
  if (selectedTemplateId) {
    const templateText = BUILT_IN_TEMPLATES[selectedTemplateId];
    if (templateText) {
      // The wizard stores answers keyed by field ID in the same order the AI
      // returned them, so we reconstruct the ordered field list from the keys.
      const fieldIds = (Object.keys(wizardAnswers) as string[]).filter(k => !k.startsWith('__'));
      return fillTemplateWithAnswers(
        templateText,
        fieldIds,
        wizardAnswers as Record<string, string | string[]>,
      );
    }
  }
  return generateDeterministicContractDraft(
    contractType,
    wizardAnswers as Record<string, string | string[]>,
    userRequest ?? undefined,
  );
}

function readDemoContracts() {
  const stored = window.localStorage.getItem(DEMO_CONTRACTS_KEY);

  if (!stored) {
    window.localStorage.setItem(DEMO_CONTRACTS_KEY, JSON.stringify([]));
    return [];
  }

  try {
    return (JSON.parse(stored) as Contract[]).map((contract) => {
      const normalized: Contract = {
        ...contract,
        selectedTemplateId: contract.selectedTemplateId ?? null,
        selectedTemplateSourceFile: contract.selectedTemplateSourceFile ?? null,
        wizardAnswers: contract.wizardAnswers ?? {},
        aiRecommendation: contract.aiRecommendation ?? null,
        aiRiskReview: contract.aiRiskReview ?? null,
        aiSummary: contract.aiSummary ?? null,
        riskFlags: contract.riskFlags ?? [],
        lastAiReviewedAt: contract.lastAiReviewedAt ?? null,
      };

      if (normalized.content === DRAFT_PLACEHOLDER) {
        normalized.content = buildInitialDraft(
          normalized.contractType,
          normalized.wizardAnswers,
          normalized.userRequest ?? undefined,
          normalized.selectedTemplateId,
        );
      }

      return normalized;
    });
  } catch {
    window.localStorage.setItem(DEMO_CONTRACTS_KEY, JSON.stringify([]));
    return [];
  }
}

function writeDemoContracts(contracts: Contract[]) {
  window.localStorage.setItem(DEMO_CONTRACTS_KEY, JSON.stringify(contracts));
}

function mapContract(row: ContractRow): Contract {
  return {
    id: row.id,
    userId: row.user_id,
    title: row.title,
    contractType: row.contract_type,
    status: row.status,
    content: row.content,
    userRequest: row.user_request,
    selectedTemplateId: row.selected_template_id ?? null,
    selectedTemplateSourceFile: row.selected_template_source_file ?? null,
    wizardAnswers: row.wizard_answers ?? {},
    aiRecommendation: row.ai_recommendation ?? null,
    aiRiskReview: row.ai_risk_review ?? null,
    aiSummary: row.ai_summary ?? null,
    riskFlags: row.risk_flags ?? [],
    lastAiReviewedAt: row.last_ai_reviewed_at ?? null,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}

export async function listContracts() {
  if (isDemoMode()) {
    return readDemoContracts().sort(
      (a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime(),
    );
  }

  const { data, error } = await supabase
    .from('contracts')
    .select(
      'id,user_id,title,contract_type,status,content,user_request,selected_template_id,selected_template_source_file,wizard_answers,ai_recommendation,ai_risk_review,ai_summary,risk_flags,last_ai_reviewed_at,created_at,updated_at',
    )
    .order('updated_at', { ascending: false });

  if (error) throw error;
  return (data ?? []).map((row: ContractRow) => mapContract(row));
}

export async function getContract(id: string) {
  if (isDemoMode()) {
    const contract = readDemoContracts().find(item => item.id === id);
    if (!contract) throw new Error('Contract not found.');
    return contract;
  }

  const { data, error } = await supabase
    .from('contracts')
    .select(
      'id,user_id,title,contract_type,status,content,user_request,selected_template_id,selected_template_source_file,wizard_answers,ai_recommendation,ai_risk_review,ai_summary,risk_flags,last_ai_reviewed_at,created_at,updated_at',
    )
    .eq('id', id)
    .single();

  if (error) throw error;
  return mapContract(data as ContractRow);
}

export async function createContract(input: CreateContractInput) {
  const title = input.title.trim();
  const contractType = input.contractType.trim();
  const userRequest = input.userRequest?.trim() || null;
  const wizardAnswers = input.wizardAnswers ?? {};

  const content =
    input.content?.trim() ||
    buildInitialDraft(contractType, wizardAnswers, userRequest, input.selectedTemplateId ?? null);

  if (!title) throw new Error('Add a title for this contract.');

  if (!CONTRACT_TYPES.includes(contractType)) {
    if (!input.selectedTemplateId) throw new Error('Choose a supported contract type.');
  }

  if (isDemoMode()) {
    const now = new Date().toISOString();
    const contract: Contract = {
      id: `demo-contract-${crypto.randomUUID()}`,
      userId: 'demo-admin',
      title,
      contractType,
      status: 'draft',
      content,
      userRequest,
      selectedTemplateId: input.selectedTemplateId ?? null,
      selectedTemplateSourceFile: input.selectedTemplateSourceFile ?? null,
      wizardAnswers,
      aiRecommendation: input.aiRecommendation ?? null,
      aiRiskReview: null,
      aiSummary: null,
      riskFlags: [],
      lastAiReviewedAt: null,
      createdAt: now,
      updatedAt: now,
    };
    writeDemoContracts([contract, ...readDemoContracts()]);
    return contract;
  }

  const { data: sessionData, error: sessionError } = await supabase.auth.getSession();
  if (sessionError) throw sessionError;

  const userId = sessionData.session?.user.id;
  if (!userId) throw new Error('You must be logged in to create a contract.');

  const { data, error } = await supabase
    .from('contracts')
    .insert({
      user_id: userId,
      title,
      contract_type: contractType,
      user_request: userRequest,
      selected_template_id: input.selectedTemplateId ?? null,
      selected_template_source_file: input.selectedTemplateSourceFile ?? null,
      wizard_answers: wizardAnswers,
      ai_recommendation: input.aiRecommendation ?? null,
      status: 'draft',
      content,
    })
    .select(
      'id,user_id,title,contract_type,status,content,user_request,selected_template_id,selected_template_source_file,wizard_answers,ai_recommendation,ai_risk_review,ai_summary,risk_flags,last_ai_reviewed_at,created_at,updated_at',
    )
    .single();

  if (error) throw error;
  return mapContract(data as ContractRow);
}

export async function updateContractContent(id: string, content: string) {
  const nextContent = content.trim();
  if (!nextContent) throw new Error('Contract content cannot be blank.');

  if (isDemoMode()) {
    const now = new Date().toISOString();
    const contracts = readDemoContracts();
    const current = contracts.find(c => c.id === id);
    if (!current) throw new Error('Contract not found.');

    const updated: Contract = {
      ...current,
      content: nextContent,
      wizardAnswers: { ...current.wizardAnswers, __manualContent: 'true' },
      updatedAt: now,
    };

    writeDemoContracts(contracts.map(c => (c.id === id ? updated : c)));
    return updated;
  }

  const { data: sessionData, error: sessionError } = await supabase.auth.getSession();
  if (sessionError) throw sessionError;

  const userId = sessionData.session?.user.id;
  if (!userId) throw new Error('You must be logged in to update a contract.');

  const current = await getContract(id);
  const wizardAnswers = { ...current.wizardAnswers, __manualContent: 'true' };

  const { data, error } = await supabase
    .from('contracts')
    .update({
      content: nextContent,
      wizard_answers: wizardAnswers,
      updated_at: new Date().toISOString(),
    })
    .eq('id', id)
    .eq('user_id', userId)
    .select(
      'id,user_id,title,contract_type,status,content,user_request,selected_template_id,selected_template_source_file,wizard_answers,ai_recommendation,ai_risk_review,ai_summary,risk_flags,last_ai_reviewed_at,created_at,updated_at',
    )
    .single();

  if (error) throw error;
  return mapContract(data as ContractRow);
}

export async function deleteContract(id: string) {
  if (isDemoMode()) {
    writeDemoContracts(readDemoContracts().filter(c => c.id !== id));
    return;
  }

  const { data: sessionData, error: sessionError } = await supabase.auth.getSession();
  if (sessionError) throw sessionError;

  const userId = sessionData.session?.user.id;
  if (!userId) throw new Error('You must be logged in to delete a contract.');

  const { error } = await supabase
    .from('contracts')
    .delete()
    .eq('id', id)
    .eq('user_id', userId);

  if (error) throw error;
}